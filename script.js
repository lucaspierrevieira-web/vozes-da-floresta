/* =========================
   INÍCIO
========================= */

function startGame() {

    resetState();

    goTo("commission");

    renderCases();

    updateStats();

}


/* =========================
   RESET
========================= */

function resetState() {

    state = {

        investigated: {},

        revealed: {},

        analyzedDocuments: 0,

        openQuestions: 0,

        recommendations: [],

        completedCases: new Set()

    };

}


/* =========================
   TROCAR TELA
========================= */

function goTo(id) {

    document
        .querySelectorAll(".screen")
        .forEach(screen => {

            screen.classList.remove("active");

        });


    document
        .getElementById(id)
        .classList.add("active");


    window.scrollTo({

        top: 0,

        behavior: "smooth"

    });

}


/* =========================
   MODAIS
========================= */

function openModal(id) {

    document
        .getElementById(id)
        .classList.add("open");

}


function closeModal(id) {

    document
        .getElementById(id)
        .classList.remove("open");

}


document
    .querySelectorAll(".modal")
    .forEach(modal => {

        modal.addEventListener(
            "click",
            event => {

                if (event.target === modal) {

                    modal.classList.remove("open");

                }

            }
        );

    });


/* =========================
   MOSTRAR CASOS
========================= */

function renderCases() {

    const grid =
        document.getElementById("caseGrid");


    grid.innerHTML =
        cases.map(c => {

            const done =
                state.completedCases.has(c.id);

            const count =
                state.revealed[c.id] || 0;


            return `

                <article class="case-card ${done ? "done" : ""}">

                    <div class="case-number">
                        ${c.number}
                    </div>

                    <h3>
                        ${c.icon}
                        ${c.title}
                    </h3>

                    <p>
                        <strong>
                            ${c.theme}
                        </strong>
                    </p>

                    <p>
                        ${c.summary}
                    </p>

                    <p class="case-source">
                        Fonte-base:
                        ${c.source}
                    </p>

                    <button
                        onclick="openCase('${c.id}')">

                        ${done
                            ? "🔎 Rever investigação"
                            : "📂 Abrir caso"
                        }

                    </button>

                    <button
                        onclick="openCase('${c.id}',true)">

                        📄 Ver documentos
                        (${count}/${c.documents.length})

                    </button>

                </article>

            `;

        })
        .join("");

}


/* =========================
   ABRIR CASO
========================= */

function openCase(id, showAll = false) {

    const c =
        cases.find(
            x => x.id === id
        );


    if (!state.revealed[id]) {

        state.revealed[id] = 0;

    }


    if (
        !showAll &&
        state.revealed[id] === 0
    ) {

        state.revealed[id] = 1;

    }


    renderCasePanel(c);

    updateStats();


    document
        .getElementById("casePanel")
        .scrollIntoView({
            behavior: "smooth"
        });

}


/* =========================
   PAINEL DO CASO
========================= */

function renderCasePanel(c) {

    const revealed =
        state.revealed[c.id] || 0;


    const docs =
        c.documents
            .map((doc, index) => {

                if (index >= revealed) {

                    return `

                        <div class="document locked">

                            <div class="document-header">

                                <div>

                                    <div class="type">
                                        DOCUMENTO BLOQUEADO
                                    </div>

                                    <h3>
                                        🔒 Documento
                                        ${index + 1}
                                    </h3>

                                </div>

                            </div>

                            <p>
                                Este documento será liberado
                                quando a comissão avançar.
                            </p>

                        </div>

                    `;

                }


                const key =
                    `${c.id}-${doc.id}`;


                const analyzed =
                    !!state.investigated[key];


                return `

                    <div class="document">

                        <div class="document-header">

                            <div>

                                <div class="type">
                                    ${doc.type}
                                </div>

                                <h3>
                                    ${doc.id}
                                    —
                                    ${doc.title}
                                </h3>

                            </div>

                            <span>
                                ${
                                    analyzed
                                        ? "✓ ANALISADO"
                                        : "📄 FONTE"
                                }
                            </span>

                        </div>


                        <p>
                            ${doc.text}
                        </p>


                        <div class="analysis">

                            <strong>
                                🔎 Leitura da fonte:
                            </strong>

                            <br>

                            ${doc.analysis}

                        </div>


                        <p class="case-source">
                            ${doc.source}
                        </p>


                        ${
                            !analyzed
                                ? `

                                    <button
                                        class="primary"
                                        onclick="analyzeDocument(
                                            '${c.id}',
                                            '${doc.id}'
                                        )">

                                        ✓ Marcar como analisado

                                    </button>

                                `
                                : ""
                        }

                    </div>

                `;

            })
            .join("");


    let nextButton;


    if (
        revealed <
        c.documents.length
    ) {

        nextButton = `

            <button
                class="primary"
                onclick="unlockNext('${c.id}')">

                🔓 Desbloquear próximo documento

            </button>

        `;

    }

    else if (
        state.completedCases.has(c.id)
    ) {

        nextButton = `

            <button
                onclick="
                    document
                    .getElementById('casePanel')
                    .classList
                    .add('hidden')
                ">

                ✓ Caso registrado

            </button>

        `;

    }

    else {

        nextButton = `

            <button
                class="primary"
                onclick="completeCase('${c.id}')">

                📜 Registrar investigação do caso

            </button>

        `;

    }


    document
        .getElementById("casePanel")
        .classList
        .remove("hidden");


    document
        .getElementById("casePanel")
        .innerHTML = `

            <div class="paper-card">

                <div class="case-label">
                    ${c.number}
                </div>

                <h2>
                    ${c.icon}
                    ${c.title}
                </h2>

                <p>
                    <strong>Tema:</strong>
                    ${c.theme}
                </p>

                ${docs}


                <div
                    class="bottom-row"
                    style="margin-top:18px">

                    ${nextButton}


                    <button
                        onclick="
                            document
                            .getElementById('casePanel')
                            .classList
                            .add('hidden')
                        ">

                        Fechar documentos

                    </button>

                </div>

            </div>

        `;

}


/* =========================
   ANALISAR DOCUMENTO
========================= */

function analyzeDocument(
    caseId,
    docId
) {

    const key =
        `${caseId}-${docId}`;


    if (!state.investigated[key]) {

        state.investigated[key] = true;

        state.analyzedDocuments++;

        state.openQuestions++;

    }


    const c =
        cases.find(
            x => x.id === caseId
        );


    renderCasePanel(c);

    updateStats();

}


/* =========================
   LIBERAR DOCUMENTO
========================= */

function unlockNext(caseId) {

    const c =
        cases.find(
            x => x.id === caseId
        );


    state.revealed[caseId] =
        Math.min(
            (state.revealed[caseId] || 0) + 1,
            c.documents.length
        );


    renderCasePanel(c);

    updateStats();

}


/* =========================
   CONCLUIR CASO
========================= */

function completeCase(caseId) {

    state.completedCases.add(caseId);


    if (
        state.openQuestions > 0
    ) {

        state.openQuestions--;

    }


    renderCases();

    renderCasePanel(
        cases.find(
            x => x.id === caseId
        )
    );

    updateStats();


    alert(
        "Caso registrado na investigação da comissão."
    );

}


/* =========================
   ESTATÍSTICAS
========================= */

function updateStats() {

    document
        .getElementById("docsCount")
        .textContent =
        state.analyzedDocuments;


    document
        .getElementById("casesCount")
        .textContent =
        `${state.completedCases.size}/4`;


    document
        .getElementById("questionsCount")
        .textContent =
        state.openQuestions;


    document
        .getElementById("recsCount")
        .textContent =
        state.recommendations.length;

}


/* =========================
   DEBATE
========================= */

function openDebate() {

    if (
        state.completedCases.size <
        cases.length
    ) {

        const proceed =
            confirm(
                "Nem todos os quatro casos foram registrados. Deseja abrir o debate mesmo assim?"
            );


        if (!proceed) {

            return;

        }

    }


    renderDebate();

    goTo("debate");

}


